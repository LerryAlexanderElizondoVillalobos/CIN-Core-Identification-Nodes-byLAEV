#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
cd "$ROOT"

for tool in dpkg-deb python3; do
  command -v "$tool" >/dev/null || { echo "Missing build dependency: $tool" >&2; exit 1; }
done

PACKAGE_ROOT="MAIN/packaging/deb"
OUTPUT_DIR="${1:-dist}"
OUTPUT_PATH="$OUTPUT_DIR/Core_Identification_Nodes.deb"

# Recreate the payload from the current source tree; never reuse an old build.
rm -rf "$PACKAGE_ROOT/opt" "$PACKAGE_ROOT/usr" "$OUTPUT_DIR"
install -d "$PACKAGE_ROOT/opt/cin-main-lobby" "$OUTPUT_DIR"
install -m 0644 MAIN/app/launcher/cin_main.py "$PACKAGE_ROOT/opt/cin-main-lobby/cin_main.py"
cp -a MAIN/app/settings "$PACKAGE_ROOT/opt/cin-main-lobby/"

# Syntax-check every shipped Python module, then discard generated bytecode.
python3 -m compileall -q "$PACKAGE_ROOT/opt/cin-main-lobby"
find "$PACKAGE_ROOT/opt/cin-main-lobby" -type d -name __pycache__ -prune -exec rm -rf {} +
find "$PACKAGE_ROOT/opt/cin-main-lobby" -type f -name '*.pyc' -delete

# Assert the two requested capabilities are in the exact payload.
test -f "$PACKAGE_ROOT/opt/cin-main-lobby/settings/deployment/engine.py"
test -f "$PACKAGE_ROOT/opt/cin-main-lobby/settings/network_access.py"
test -f "$PACKAGE_ROOT/opt/cin-main-lobby/cin_main.py"

dpkg-deb --build --root-owner-group "$PACKAGE_ROOT" "$OUTPUT_PATH"

# Inspect metadata and contents; reject stale/incorrect package identity.
test "$(dpkg-deb --field "$OUTPUT_PATH" Package)" = "core-identification-nodes"
test "$(dpkg-deb --field "$OUTPUT_PATH" Architecture)" = "all"
dpkg-deb --extract "$OUTPUT_PATH" "$OUTPUT_DIR/inspect"
test -f "$OUTPUT_DIR/inspect/opt/cin-main-lobby/settings/deployment/engine.py"
test -f "$OUTPUT_DIR/inspect/opt/cin-main-lobby/settings/network_access.py"
rm -rf "$OUTPUT_DIR/inspect"
dpkg-deb --info "$OUTPUT_PATH"
printf '\nOfficial package candidate: %s\n' "$OUTPUT_PATH"
